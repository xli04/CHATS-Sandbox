"""Post-analysis for swe-recovery manifests.

Reports TWO coverage rates per instance:
  raw     = manifest_similarity over ALL files (penalizes regenerated bytecode)
  source  = same, excluding regenerable byproducts (*.pyc, __pycache__/,
            .pytest_cache/, *.egg-info/, build/) — i.e. the files git itself
            ignores. This is the meaningful "did the repo come back" number.

Also prints the breakdown of what is uncovered so the gap is never a
mystery: original-missing (real recovery failures) vs leftover-byproduct
(regenerated cache, not a failure).
"""
import json, os, sys, re

REGEN = re.compile(r"(^|/)(__pycache__|\.pytest_cache|\.mypy_cache|\.tox)/|\.pyc$|\.pyo$|(^|/)build/|\.egg-info(/|$)")


def is_regen(p):
    return bool(REGEN.search(p))


def filt(m, source_only):
    if not source_only:
        return m
    return {k: v for k, v in m.items() if not is_regen(k)}


def sim(a, b):
    paths = set(a) | set(b)
    if not paths:
        return 1.0
    return sum(1 for p in paths if a.get(p) == b.get(p)) / len(paths)


def analyze(d):
    s0 = json.load(open(os.path.join(d, "s0.json")))
    s1 = json.load(open(os.path.join(d, "s1.json")))
    s2 = json.load(open(os.path.join(d, "s2.json")))
    out = {}
    for label, src in (("raw", False), ("source", True)):
        a, b, c = filt(s0, src), filt(s1, src), filt(s2, src)
        # gap breakdown on the source-filtered S0 vs S2
        paths = set(a) | set(c)
        missing = [p for p in paths if p in a and (p not in c or a[p] != c[p])]  # original not back
        leftover = [p for p in paths if p not in a and p in c]                   # extra after restore
        out[label] = {
            "damage": round(sim(a, b), 4),
            "coverage": round(sim(a, c), 4),
            "n0": len(a),
            "orig_not_restored": len(missing),
            "leftover": len(leftover),
            "missing_sample": sorted(missing)[:10],
        }
    return out


if __name__ == "__main__":
    root = sys.argv[1] if len(sys.argv) > 1 else "results/swe-recovery"
    print(f"{'instance':<26} {'raw_cov':>8} {'src_cov':>8} {'src_damage':>10} {'orig_lost':>9} {'leftover':>8}")
    for name in sorted(os.listdir(root)):
        d = os.path.join(root, name)
        if not os.path.isdir(d) or not os.path.exists(os.path.join(d, "s2.json")):
            continue
        r = analyze(d)
        print(f"{name:<26} {r['raw']['coverage']:>8.3f} {r['source']['coverage']:>8.3f} "
              f"{r['source']['damage']:>10.3f} {r['source']['orig_not_restored']:>9} {r['source']['leftover']:>8}")
        if r["source"]["orig_not_restored"]:
            print(f"    ! source files NOT restored: {r['source']['missing_sample']}")
